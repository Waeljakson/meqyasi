// صلاحية الاستجابة: نمط الإجابة الواحدة وسرعة الإنجاز
function validity(scale, r) {
  const notes = [], a = r.answers || [];
  const uniform = a.length >= 7 && a.every(x => x === a[0]);
  const fast = r.secs && r.secs / Math.max(1, a.length) < 1.5;
  if (uniform) notes.push('إجابة واحدة لكل البنود');
  if (fast) notes.push('زمن إنجاز قصير جداً');
  return { ok: !notes.length, text: notes.length ? notes.join('، ') : 'مقبولة' };
}
// البنود الأعلى استجابة (في النصف الأعلى من مدى البند)
function topItems(scale, r) {
  const out = [];
  (r.answers || []).forEach((k, i) => {
    const it = scale.items[i]; if (!it) return;
    const opts = it.opts || scale.options, vals = opts.map(o => o.v), mx = Math.max(...vals), mn = Math.min(...vals);
    const v = itemValue(scale, i, k);
    if (mx > mn && (v - mn) / (mx - mn) >= 0.66) out.push({ n: i + 1, t: it.t, a: opts[k].t, max: v === mx });
  });
  return out;
}
function referralLevel(top, urgent) {
  if (urgent) return { cls: 'l3', title: 'إحالة عاجلة', text: 'تقييم متخصص خلال 24 ساعة، مع عدم ترك الحالة دون مرافق.' };
  if (top >= 3) return { cls: 'l3', title: 'إحالة ذات أولوية', text: 'تقييم متخصص خلال أسبوع.' };
  if (top === 2) return { cls: 'l2', title: 'إحالة اعتيادية', text: 'تقييم متخصص خلال 2–4 أسابيع.' };
  if (top === 1) return { cls: 'l1', title: 'متابعة', text: 'دعم ذاتي وأسري وإعادة القياس بعد 2–4 أسابيع؛ الإحالة إن استمرت المؤشرات أو زادت.' };
  return { cls: 'l0', title: 'لا حاجة للإحالة حالياً', text: 'لا مؤشرات مرتفعة في المقاييس المطبقة.' };
}
function specialistFor(age, top, urgent, domains) {
  const out = [];
  if (age < 18) out.push(top >= 3 || urgent ? 'طبيب نفسي للأطفال والمراهقين' : 'أخصائي نفسي للأطفال والمراهقين', 'المرشد الطلابي للتنسيق المدرسي');
  else out.push(top >= 3 || urgent ? 'طبيب نفسي' : 'أخصائي نفسي إكلينيكي');
  if (domains.includes('perinatal')) out.push('طبيبة النساء والولادة');
  if (age >= 60) out.push('طبيب الأسرة أو طب المسنين');
  return out;
}

