// ---------- التصحيح ----------
function itemValue(scale, i, optIndex) {
  const it = scale.items[i];
  const opts = it.opts || scale.options;
  let v = opts[optIndex].v;
  if (it.r) {
    const vals = opts.map(o => o.v);
    v = Math.max(...vals) + Math.min(...vals) - v;
  }
  return v;
}
function pickBand(bands, score) {
  return bands.find(b => score <= b.max) || bands[bands.length - 1];
}
function scoreScale(scale, answers) {
  const vals = answers.map((a, i) => itemValue(scale, i, a));
  const sc = scale.scoring;
  const sum = vals.reduce((a, b) => a + b, 0);
  const total = sc.type === 'mean' ? Math.round((sum / vals.length) * 100) / 100 : sum * (sc.mult || 1);
  const subs = (sc.subs || []).map(s => {
    const raw = s.items.reduce((a, n) => a + vals[n - 1], 0);
    const score = s.type === 'mean' ? Math.round((raw / s.items.length) * 100) / 100 : raw * (s.mult || 1);
    const out = { name: s.name, score, domain: s.domain || null, level: 0, label: '' };
    if (s.bands) { const b = pickBand(s.bands, score); out.level = b.level; out.label = b.label; }
    if (s.cut != null) { out.flag = score >= s.cut; out.label = out.flag ? 'مرتفع' : 'ضمن المعدل'; out.level = out.flag ? 2 : 0; }
    return out;
  });
  let level, band;
  if (sc.noTotalBand) {
    level = Math.max(...subs.map(s => s.level));
    band = subs.map(s => s.name + ': ' + s.label).join(' · ');
  } else {
    const b = pickBand(sc.bands, total); level = b.level; band = b.label;
  }
  const urgent = (scale.alerts || []).some(a => vals[a.item - 1] >= a.min);
  if (urgent) level = 3;
  return { total, max: sc.max, band, level, subs, urgent };
}
function scalesFor(age, gender) {
  return SCALES.filter(s => age >= (s.minAge || 0) && age <= (s.maxAge || 200) && (!s.gender || s.gender === gender));
}
function stageOf(age) { return age <= 12 ? 'child' : age <= 17 ? 'teen' : 'adult'; }

