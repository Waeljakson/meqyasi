function buildPlan(scale, result) {
  let domain = scale.domain;
  if (domain === 'mixed') {
    const top = result.subs.slice().sort((a, b) => b.level - a.level || b.score - a.score)[0];
    domain = top && top.domain ? top.domain : 'stress';
  }
  const p = PLANS[domain] || PLANS.wellbeing;
  const steps = p.weeks.slice();
  const referral = result.level >= 2
    ? 'الإحالة: احجز موعداً مع أخصائي نفسي' + (result.level === 3 ? ' أو طبيب نفسي خلال أيام' : ' خلال أسبوعين') + '، واصطحب هذا التقرير.'
    : 'المتابعة: أعد المقياس بعد أسبوعين إلى أربعة، واستشر مختصاً إذا استمرت المؤشرات أو زادت.';
  return { goal: p.goal, steps, habits: BASE_HABITS, referral };
}

